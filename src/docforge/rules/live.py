"""What a live rule does: Vale rules for `avoid`, work-order text for `guidance`.

Approving or closing a rule refreshes vale/DocForgeLearned/ inside the rules
folder (for people to inspect), never this public repository's styles/.
`lint_config` rebuilds the learned style from the rules themselves each time.
"""

from __future__ import annotations

from contextlib import contextmanager
from pathlib import Path
import shutil
import tempfile
from typing import Iterator

import yaml

from .model import Rule, TOOLS_ROOT, load_rules

LEARNED_STYLE = "DocForgeLearned"


def vale_rule(rule: Rule) -> dict:
    tag = f"learned rule {rule.id}"
    if rule.replace:
        return {"extends": "substitution", "message": f"{rule.message} Use '%s' instead of '%s' ({tag}).",
                "level": rule.level, "ignorecase": rule.ignorecase, "swap": {rule.pattern: rule.replace},
                "action": {"name": "replace"}}
    return {"extends": "existence", "message": f"{rule.message} ('%s'; {tag})", "level": rule.level,
            "ignorecase": rule.ignorecase, "nonword": False, "tokens": [rule.pattern]}


def write_style(rules: list[Rule], styles: Path) -> None:
    folder = styles / LEARNED_STYLE
    folder.mkdir(parents=True, exist_ok=True)
    for rule in rules:
        (folder / f"{rule.id}.yml").write_text(
            f"# Generated by DocForge from {rule.id} ({rule.title}). Do not edit; edit the rule instead.\n"
            + yaml.safe_dump(vale_rule(rule), sort_keys=False, allow_unicode=True), encoding="utf-8")


def live_rules(folder: Path) -> list[Rule]:
    return [r for r in load_rules(folder) if r.effective_status() == "live"]


def sync_live(folder: Path) -> None:
    """Rewrite vale/DocForgeLearned/ so it holds exactly the live avoid rules."""
    target = folder / "vale" / LEARNED_STYLE
    if target.is_dir():
        shutil.rmtree(target)
    avoid = [r for r in live_rules(folder) if r.kind == "avoid"]
    if avoid:
        write_style(avoid, folder / "vale")


@contextmanager
def lint_config(folder: Path) -> Iterator[Path | None]:
    """A Vale config with the house style plus live avoid rules, or None if there are none.

    Built from the rule files each time (status and content hash checked), never
    from the generated vale/ folder, so an edited or broken rule is not applied.
    """
    avoid = [r for r in live_rules(folder) if r.kind == "avoid"]
    if not avoid:
        yield None
        return
    with tempfile.TemporaryDirectory() as tmp:
        styles = Path(tmp) / "styles"
        shutil.copytree(TOOLS_ROOT / "styles" / "DocForge", styles / "DocForge")
        write_style(avoid, styles)
        config = Path(tmp) / ".vale.ini"
        config.write_text(f"StylesPath = {styles}\nMinAlertLevel = suggestion\n\n[*.md]\n"
                          f"BasedOnStyles = DocForge, {LEARNED_STYLE}\n", encoding="utf-8")
        yield config


@contextmanager
def single_rule_config(rule: Rule) -> Iterator[Path]:
    """A Vale config that runs only this rule, for testing it."""
    with tempfile.TemporaryDirectory() as tmp:
        styles = Path(tmp) / "styles"
        write_style([rule], styles)
        config = Path(tmp) / ".vale.ini"
        config.write_text(f"StylesPath = {styles}\nMinAlertLevel = suggestion\n\n[*.md]\n"
                          f"BasedOnStyles = {LEARNED_STYLE}\n", encoding="utf-8")
        yield config


def guidance_lines(folder: Path, pages: list[str] | None = None) -> list[str]:
    """Markdown bullets for live guidance rules that apply to any of `pages` (all if None)."""
    lines = []
    for rule in live_rules(folder):
        if rule.kind != "guidance":
            continue
        if pages is not None and rule.applies_to and not any(a in p for a in rule.applies_to for p in pages):
            continue
        scope = f" (applies to pages containing: {', '.join(rule.applies_to)})" if rule.applies_to else ""
        lines.append(f"- **{rule.id}** {rule.guidance.strip()}{scope}")
    return lines
