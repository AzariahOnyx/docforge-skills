"""Cross-source status per claim, and the clarification questions they raise.

Status rules, checked in this order:

- conflicting:       PRD evidence and code marked "contradicts"
- needs_engineering: the researcher recorded a question the code cannot answer
- confirmed:         PRD evidence and code marked "supports"
- prd_only:          PRD evidence and no supporting code
- code_only:         supporting code and no PRD evidence
- unknown:           neither

conflicting, needs_engineering and code_only each raise a question (X1, X2, ...)
for the clarification register. Contradictions are never resolved here.
"""

from __future__ import annotations

from pathlib import Path
from typing import Literal

from pydantic import BaseModel

from .claims import Claim, ClaimsFile
from .packet import ResearchError

Status = Literal["confirmed", "prd_only", "code_only", "conflicting", "unknown", "needs_engineering"]
STATUS_ORDER: tuple[Status, ...] = ("conflicting", "needs_engineering", "confirmed", "prd_only", "code_only", "unknown")
BLOCK_START = "<!-- docforge:cross-source:start -->"
BLOCK_END = "<!-- docforge:cross-source:end -->"


class ClaimResult(BaseModel):
    claim_id: str
    statement: str
    status: Status
    prd_sources: list[str]
    supporting_code: list[str]
    contradicting_code: list[str]
    question_id: str | None = None
    question: str | None = None


def _cite(c) -> str:
    return f"{c.path} {c.lines} @ {c.commit[:12]}"


def classify(claim: Claim) -> Status:
    has_prd = bool(claim.prd)
    supports = any(c.relation == "supports" for c in claim.code)
    contradicts = any(c.relation == "contradicts" for c in claim.code)
    if has_prd and contradicts:
        return "conflicting"
    if claim.needs_engineering:
        return "needs_engineering"
    if has_prd and supports:
        return "confirmed"
    if has_prd:
        return "prd_only"
    if supports:
        return "code_only"
    return "unknown"


def _question(claim: Claim, status: Status) -> str | None:
    cid = claim.claim_id
    if status == "conflicting":
        cited = "; ".join(_cite(c) + (f" ({c.note})" if c.note else "") for c in claim.code if c.relation == "contradicts")
        sources = ", ".join(sorted({p.source_id for p in claim.prd}))
        return (f"{cid}: the PRD ({sources}) and the code ({cited}) disagree about \"{claim.statement}\". "
                "Which behavior is intended? Documentation keeps both until this is answered.")
    if status == "needs_engineering":
        return f"{cid}: {claim.needs_engineering.strip()}"
    if status == "code_only":
        cited = "; ".join(_cite(c) for c in claim.code if c.relation == "supports")
        return (f"{cid}: the code ({cited}) implements \"{claim.statement}\", but the PRD does not state it. "
                "Is this intended behavior that the documentation may describe?")
    return None


def evaluate(claims: ClaimsFile) -> list[ClaimResult]:
    results: list[ClaimResult] = []
    number = 0
    for claim in claims.claims:
        status = classify(claim)
        question = _question(claim, status)
        qid = None
        if question:
            number += 1
            qid = f"X{number}"
        results.append(ClaimResult(
            claim_id=claim.claim_id, statement=claim.statement, status=status,
            prd_sources=sorted({p.source_id for p in claim.prd}),
            supporting_code=[_cite(c) for c in claim.code if c.relation == "supports"],
            contradicting_code=[_cite(c) for c in claim.code if c.relation == "contradicts"],
            question_id=qid, question=question,
        ))
    return results


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_report(results: list[ClaimResult], *, verified: bool) -> str:
    counts = {s: sum(r.status == s for r in results) for s in STATUS_ORDER}
    lines = [
        "# Cross-source check",
        "",
        "Generated by `docforge research check` from `analysis/claims.json`. Statuses compare what the PRD states "
        "with what the cited code does; they are not product verification.",
        "",
        "Code evidence: " + ("verified against a local checkout." if verified else
                              "NOT verified (no local checkout was supplied)."),
        "",
        "## Summary",
        "",
        "| Status | Claims |",
        "| --- | --- |",
    ]
    lines += [f"| {s} | {counts[s]} |" for s in STATUS_ORDER]
    lines += ["", "## Claims", "", "| Claim | Status | Statement | PRD | Supporting code | Contradicting code | Question |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for r in results:
        lines.append("| " + " | ".join([
            r.claim_id, r.status, _cell(r.statement), ", ".join(r.prd_sources) or "none",
            _cell("; ".join(r.supporting_code)) or "none", _cell("; ".join(r.contradicting_code)) or "none",
            r.question_id or "none",
        ]) + " |")
    lines += ["", "## Clarification questions", ""]
    questions = [r for r in results if r.question]
    lines += [f"- **{r.question_id}** ({r.status}) {r.question}" for r in questions] or ["None."]
    return "\n".join(lines) + "\n"


def render_register_block(results: list[ClaimResult]) -> str:
    questions = [r for r in results if r.question]
    body = [BLOCK_START, "", "## Cross-source questions", "",
            "Generated by `docforge research check`; rerunning replaces this section. Do not edit it by hand.", ""]
    body += [f"- **{r.question_id}** ({r.status}) {r.question}" for r in questions] or ["None."]
    return "\n".join(body + ["", BLOCK_END])


def update_register(register: Path, results: list[ClaimResult]) -> None:
    """Insert or replace the generated block in the clarification register."""
    if not register.is_file():
        raise ResearchError(f"missing {register}; the Analyzer stage writes it before research")
    text = register.read_text(encoding="utf-8")
    block = render_register_block(results)
    start, end = text.find(BLOCK_START), text.find(BLOCK_END)
    if (start == -1) != (end == -1) or (start != -1 and end < start):
        raise ResearchError(f"{register.name} has a damaged cross-source block; fix its markers by hand")
    if start == -1:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    else:
        text = text[:start] + block + text[end + len(BLOCK_END):]
    register.write_text(text, encoding="utf-8")
